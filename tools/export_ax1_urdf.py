#!/usr/bin/env python3
"""Refresh the old ax_1.urdf name from the authoritative articulated Xacro."""
from pathlib import Path
import shutil
import re
import xacro
from ament_index_python.packages import get_package_share_directory

root = Path(__file__).resolve().parents[1]
share = Path(get_package_share_directory('ax_description'))
description = xacro.process_file(str(share / 'urdf/ax.urdf.xacro'), mappings={
    'gripper_model': 'epick', 'sensor_robot_id': 'robot_1', 'frame_prefix': 'robot_1/'}).toxml()
description = re.sub(r'<!--[^>]*autogenerated by xacro from .*?-->', '<!-- Generated from ax_description/urdf/ax.urdf.xacro -->', description)
header = '<!-- Generated from ax.urdf.xacro. Launch robot_test.launch.py for controllers and sensor bridges. -->\n'
destination = root / 'src/ax_description/urdf/ax_1.urdf'
description = description.replace('?>', '?>\n' + header, 1)
destination.write_text(description + '\n', encoding='utf-8')
installed = share / 'urdf/ax_1.urdf'
if installed.resolve() != destination.resolve():
    shutil.copyfile(destination, installed)
print('Updated compatibility model:', destination)
