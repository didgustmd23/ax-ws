#!/usr/bin/env python3
"""Split assembled OBJ assets without changing coordinates, units or topology.

Run from any directory. AX_1/AX_2 retain every source object; AX_Box is a
separate prop asset. Only AX_1 gets the existing support/column derivation.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil


ROOT = Path(__file__).resolve().parents[1]
MESHES = ROOT / 'src/ax_description/meshes'
COORDINATES = ('Original assembled coordinates, orientation, scale and units '
               'preserved; no recentering. Source units assumed mm.')


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_obj(path):
    """Resolve face indices at their declaration, including negative indices."""
    tables = {key: [] for key in ('v', 'vt', 'vn')}
    objects = {}
    libraries = []
    current = None
    material, smoothing = None, 'off'
    for number, line in enumerate(path.read_text().splitlines(), 1):
        words = line.split('#', 1)[0].split()
        if not words:
            continue
        key = words[0]
        if key in tables:
            tables[key].append(' '.join(words))
        elif key == 'mtllib':
            libraries.extend(words[1:])
        elif key == 'o':
            current = ' '.join(words[1:])
            objects.setdefault(current, [])
        elif key == 'g' and current is None:
            current = ' '.join(words[1:])
            objects.setdefault(current, [])
        elif key == 'usemtl':
            material = ' '.join(words[1:])
        elif key == 's':
            smoothing = ' '.join(words[1:])
        elif key == 'f':
            if current is None or len(words) < 4:
                raise ValueError(f'{path}:{number}: face without object or triangle')
            face = []
            for token in words[1:]:
                fields = token.split('/')
                if len(fields) > 3 or not fields[0]:
                    raise ValueError(f'{path}:{number}: invalid face token {token}')
                indices = []
                for kind, field in zip(tables, fields):
                    if not field:
                        indices.append(None)
                        continue
                    index = int(field)
                    resolved = index - 1 if index > 0 else len(tables[kind]) + index
                    if index == 0 or not 0 <= resolved < len(tables[kind]):
                        raise ValueError(f'{path}:{number}: invalid {kind} index {index}')
                    indices.append(resolved)
                face.append(tuple(indices))
            objects[current].append((face, material, smoothing))
    return tables, objects, libraries


def write_part(path, name, tables, faces, libraries):
    """Compact each index table independently, retaining face order and states."""
    used = [sorted({corner[i] for face, _, _ in faces for corner in face
                    if len(corner) > i and corner[i] is not None}) for i in range(3)]
    maps = [{index: n + 1 for n, index in enumerate(indices)} for indices in used]
    lines = ['# Generated by tools/split_robot_meshes.py; assembled coordinates preserved.']
    lines.extend(f'mtllib {library}' for library in libraries)
    for (kind, values), indices in zip(tables.items(), used):
        lines.extend(values[i] for i in indices)
    lines.extend([f'o {name}', f'g {name}'])
    previous = object()
    for face, material, smoothing in faces:
        state = (material, smoothing)
        if state != previous:
            if material is not None:
                lines.append(f'usemtl {material}')
            lines.append(f's {smoothing}')
            previous = state
        lines.append('f ' + ' '.join('/'.join(
            '' if index is None else str(maps[i][index])
            for i, index in enumerate(corner)) for corner in face))
    path.write_text('\n'.join(lines) + '\n')
    return dict(file=path.name, vertices=len(used[0]),
                texture_coordinates=len(used[1]), normals=len(used[2]), faces=len(faces),
                sha256=sha256(path))


def part_filename(name):
    return name.lower().replace('ax1_', 'ax_', 1).replace('ax_2_', 'ax_', 1) + '.obj'


def split_obj(source, output):
    tables, objects, libraries = read_obj(source)
    # Validate all inputs before creating or overwriting outputs.
    names = [part_filename(name) for name in objects]
    if len(names) != len(set(names)) or any(Path(name).name != name for name in names):
        raise ValueError(f'{source}: duplicate or unsafe output names')
    for library in libraries:
        if Path(library).name != library or not (source.parent / library).is_file():
            raise ValueError(f'{source}: missing or unsafe material library {library}')
    output.mkdir(parents=True, exist_ok=True)
    manifest = dict(source=os.path.relpath(source.resolve(), output.resolve()),
                    source_sha256=sha256(source), coordinate_policy=COORDINATES,
                    material_libraries={name: sha256(source.parent / name) for name in libraries},
                    excluded_objects=[], parts=[])
    for name, faces in objects.items():
        info = write_part(output / part_filename(name), name, tables, faces, libraries)
        manifest['parts'].append(dict(source_object=name, **info))
    for library in libraries:
        shutil.copyfile(source.parent / library, output / library)
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    return manifest


def split_column(directory):
    """Keep the existing geometry-based ownership: central tube + three rings."""
    source = directory / 'arm_01_fixed.obj'
    tables, objects, _ = read_obj(source)
    faces = next(iter(objects.values()))
    positions = [tuple(round(float(x), 4) for x in line.split()[1:4])
                 for line in tables['v']]
    parents = list(range(len(positions)))

    def find(i):
        while parents[i] != i:
            parents[i] = parents[parents[i]]
            i = parents[i]
        return i

    coincident = {}
    for i, point in enumerate(positions):
        if point in coincident:
            parents[find(i)] = find(coincident[point])
        else:
            coincident[point] = i
    for face, _, _ in faces:
        for corner in face[1:]:
            parents[find(corner[0])] = find(face[0][0])
    groups = {}
    for face in faces:
        groups.setdefault(find(face[0][0][0]), []).append(face)
    assignments = {'column': [], 'support': []}
    components = []
    column_count = 0
    tube_length = None
    for group in groups.values():
        points = [positions[c[0]] for face, _, _ in group for c in face]
        lo = [min(p[i] for p in points) for i in range(3)]
        hi = [max(p[i] for p in points) for i in range(3)]
        tube = lo[:2] == [80., 85.] and hi[:2] == [280., 285.]
        ring = lo[:2] == [76., 81.] and hi[:2] == [284., 289.]
        part = 'column' if tube or ring else 'support'
        if tube:
            tube_length = (hi[2] - lo[2]) * .001
        column_count += int(tube or ring)
        assignments[part].extend(group)
        components.append(dict(bounds_mm=[lo, hi], assignment=part))
    if column_count != 4 or tube_length is None:
        raise ValueError('Expected one central tube and three collars; inspect geometry before assigning')
    report = dict(source=source.name, source_sha256=sha256(source),
                  classification='Central cylindrical surface and 3 collars rotate; all other '
                                 'components remain fixed. Geometry-based assignment; '
                                 'mechanical confirmation required.',
                  tube_length_m=tube_length, components=components, outputs=[])
    for part, group in assignments.items():
        material = 'ax_column_orange' if part == 'column' else 'ax_support_dark_gray'
        colored = [(face, material, smooth) for face, _, smooth in group]
        info = write_part(directory / f'arm_01_{part}.obj', f'arm_01_{part}', tables,
                          colored, ['ax_column_colors.mtl'])
        report['outputs'].append(dict(part=part, **info))
    # These two derived assets intentionally override source material selection.
    (directory / 'ax_column_colors.mtl').write_text(
        '# AX support/column display colors; original AX_1.mtl is unchanged.\n'
        'newmtl ax_support_dark_gray\nKa 0.08 0.08 0.08\nKd 0.22 0.25 0.30\n'
        'Ks 0.12 0.12 0.12\nNs 24\nd 1\nillum 2\n\n'
        'newmtl ax_column_orange\nKa 0.08 0.08 0.08\nKd 1.0 0.45 0.05\n'
        'Ks 0.12 0.12 0.12\nNs 24\nd 1\nillum 2\n')
    (directory / 'column_split_manifest.json').write_text(json.dumps(report, indent=2) + '\n')
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, default=MESHES / 'parts')
    args = parser.parse_args()
    for name, folder in [('AX_1', 'AX_1'), ('AX_2', 'AX_2'), ('AX_Box', 'boxes')]:
        manifest = split_obj(MESHES / f'{name}.obj', args.output_dir / folder)
        print(name, len(manifest['parts']), 'objects,',
              sum(p['faces'] for p in manifest['parts']), 'faces')
    split_column(args.output_dir / 'AX_1')


if __name__ == '__main__':
    main()
