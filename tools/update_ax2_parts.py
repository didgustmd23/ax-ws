#!/usr/bin/env python3
"""AX_2 원본의 7개 오브젝트를 좌표·면·재질을 보존해 활성 메시로 분리한다."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MESHES = ROOT / 'src/ax_description/meshes'
NAMES = {
    'AX_2_Shelf': 'ax_shelf', 'AX_2_Body': 'ax_body',
    'AX_2_Tire_01': 'ax_tire_right_front', 'AX_2_Tire_02': 'ax_tire_left_front',
    'AX_2_Tire_03': 'ax_tire_right_rear', 'AX_2_Tire_04': 'ax_tire_left_rear',
    'AX_2_Right': 'ax_right',
}


def generated():
    source = MESHES / 'AX_2.obj'
    attrs = {key: [] for key in ('v', 'vt', 'vn')}
    objects = {}
    active = None
    for line in source.read_text(encoding='utf-8').splitlines():
        fields = line.split()
        if not fields:
            continue
        kind = fields[0]
        if kind in attrs:
            attrs[kind].append(line)
        elif kind == 'o':
            active = fields[1]
            objects[active] = []
        elif active and kind == 'f':
            face = []
            for token in fields[1:]:
                face.append(tuple((int(value)-1 if int(value)>0 else len(attrs[key])+int(value))
                                  if value else None
                                  for key, value in zip(attrs, token.split('/'))))
            objects[active].append(('f', face))
        elif active and kind in ('usemtl', 's', 'g'):
            objects[active].append((kind, line))
    if set(objects) != set(NAMES):
        raise ValueError('CAD object names changed; update NAMES explicitly: ' + repr(set(objects)))
    files = {'AX_2.mtl': (MESHES / 'AX_2.mtl').read_bytes()}
    manifest = dict(source='../../AX_2.obj', source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                    coordinate_policy='Original assembled coordinates, orientation, scale and mm units preserved; no recentering.',
                    material_libraries={'AX_2.mtl': hashlib.sha256(files['AX_2.mtl']).hexdigest()},
                    excluded_objects=[], parts=[])
    for obj, name in NAMES.items():
        records = objects[obj]
        used = {key: sorted({face[i] for kind, record in records if kind=='f'
                            for face in record if len(face)>i and face[i] is not None})
                for i, key in enumerate(attrs)}
        maps = {key: {old: new+1 for new, old in enumerate(indices)} for key, indices in used.items()}
        lines = ['# Generated by tools/update_ax2_parts.py; assembled CAD coordinates in mm.', 'mtllib AX_2.mtl']
        for key, indices in used.items():
            lines.extend(attrs[key][i] for i in indices)
        lines.append('o ' + obj)
        for kind, record in records:
            if kind == 'f':
                lines.append('f ' + ' '.join('/'.join(str(maps[key][value]) if value is not None else ''
                                  for key, value in zip(attrs, face)) for face in record))
            else:
                lines.append(record)
        data = ('\n'.join(lines)+'\n').encode('utf-8')
        files[name+'.obj'] = data
        manifest['parts'].append(dict(source_object=obj, file=name+'.obj', vertices=len(used['v']),
            texture_coordinates=len(used['vt']), normals=len(used['vn']),
            faces=sum(kind=='f' for kind, _ in records), sha256=hashlib.sha256(data).hexdigest()))
    files['manifest.json'] = (json.dumps(manifest, indent=2)+'\n').encode('utf-8')
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    folder = MESHES / 'parts/AX_2'
    files = generated()
    unexpected = {p.name for p in folder.glob('*.obj')} - files.keys()
    if unexpected:
        raise SystemExit('Archive removed CAD parts before regeneration: ' + repr(unexpected))
    for name, data in files.items():
        path = folder/name
        if args.check:
            if not path.is_file() or path.read_bytes()!=data:
                raise SystemExit('Generated part differs: ' + name)
        else:
            path.write_bytes(data)
    print('AX_2: all 7 parts, OBJ indices, materials and manifest match current CAD source.')


if __name__ == '__main__':
    main()
